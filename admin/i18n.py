def tr(key: str, lang: str) -> str:
    lang = lang if lang in TEXTS else "uz"
    return TEXTS[lang].get(key) or TEXTS["uz"].get(key) or key


PERMS = {
    "super": {"view", "stop", "ban", "mutate", "ads", "shop", "settings", "staff"},
    "moderator": {"view", "stop", "ban"},
    "ads": {"view", "ads"},
}


def can(role: str | None, perm: str) -> bool:
    if not role:
        return False
    return perm in PERMS.get(role, set())
